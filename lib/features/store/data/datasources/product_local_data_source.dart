/// Local, JSON-shaped menu. A remote data source can replace it later
/// without touching the domain or presentation layers.
abstract class ProductDataSource {
  Future<List<CategoryModel>> fetchCategories();
  Future<List<ProductModel>> fetchProducts();
  Future<String> submitOrder(Map<String, int> quantitiesByProductId);
}

@LazySingleton(as: ProductDataSource)
class ProductLocalDataSource implements ProductDataSource {
  int _orderSeq = 1000;

  Future<void> _latency() => Future<void>.delayed(
    const Duration(milliseconds: AppConstants.fakeLatencyMs),
  );

  @override
  Future<List<CategoryModel>> fetchCategories() async {
    await _latency();
    return _categories.map(CategoryModel.fromJson).toList();
  }

  @override
  Future<List<ProductModel>> fetchProducts() async {
    await _latency();
    return _products.map(ProductModel.fromJson).toList();
  }

